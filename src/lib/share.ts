"use client";

import type { Draft } from "./agent-client";

/**
 * Share links for generated guides without a database: the draft is deflate-compressed and base64url-encoded
 * into the URL fragment (#share=…). Fragments are never sent to the server. Typical guide: a few KB.
 */

const toB64url = (bytes: Uint8Array) => {
  let s = "";
  for (const b of bytes) s += String.fromCharCode(b);
  return btoa(s).replace(/\+/g, "-").replace(/\//g, "_").replace(/=+$/, "");
};
const fromB64url = (s: string) => Uint8Array.from(atob(s.replace(/-/g, "+").replace(/_/g, "/")), (c) => c.charCodeAt(0));

async function pipe(bytes: Uint8Array, stream: CompressionStream | DecompressionStream) {
  return new Uint8Array(await new Response(new Blob([bytes as BlobPart]).stream().pipeThrough(stream)).arrayBuffer());
}

export async function encodeDraft(d: Draft): Promise<string> {
  const json = new TextEncoder().encode(JSON.stringify({ guide: d.guide, logo: d.logo, research: d.research }));
  return toB64url(await pipe(json, new CompressionStream("deflate-raw")));
}

export async function decodeDraft(s: string): Promise<Draft | null> {
  try {
    const d = JSON.parse(new TextDecoder().decode(await pipe(fromB64url(s), new DecompressionStream("deflate-raw")))) as Draft;
    // Shared guides are generated by definition; never let a link present itself as reviewed or tested.
    if (!d?.guide?.app || !Array.isArray(d.guide.steps)) return null;
    d.guide._generated = true;
    for (const x of [...d.guide.steps, ...(d.guide.blockers ?? []), ...(d.guide.cases ?? [])]) if (x.ev === "tested") x.ev = "uncertain";
    return d;
  } catch {
    return null;
  }
}

export async function shareUrl(d: Draft) {
  return `${location.origin}/draft#share=${await encodeDraft(d)}`;
}
